import * as fs from 'fs';
import * as os from 'os';
import * as path from 'path';
import { afterEach, describe, expect, it } from 'vitest';
import { firstUserPrompt } from '../sessionStats';
import type { SessionEvent } from '../types/sessionEvent';
import { ClaudeCodeProvider } from './claudeCode';

const dirs: string[] = [];
afterEach(() => {
  for (const dir of dirs.splice(0)) fs.rmSync(dir, { recursive: true, force: true });
});

/** A transcript under a project directory named the way Claude Code names it. */
function transcript(projectDir: string, lines: unknown[]): string {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'sidekick-claude-labels-'));
  dirs.push(root);
  const dir = path.join(root, projectDir);
  fs.mkdirSync(dir, { recursive: true });
  const file = path.join(dir, 'session.jsonl');
  fs.writeFileSync(file, lines.map((line) => JSON.stringify(line)).join('\n') + '\n');
  return file;
}

const user = (content: unknown, extra: Record<string, unknown> = {}) => ({
  type: 'user',
  timestamp: '2026-11-01T10:00:00.000Z',
  message: { role: 'user', content },
  ...extra,
});

describe('Claude Code session labels', () => {
  const provider = new ClaudeCodeProvider();

  it('skips harness lines and labels the session with the first typed prompt', async () => {
    const file = transcript('-w-app', [
      user(
        '<local-command-caveat>Caveat: The messages below were generated by the user while running local commands.</local-command-caveat>',
      ),
      user('Injected context', { isMeta: true }),
      user([{ type: 'text', text: '<system-reminder>be brief</system-reminder>' }]),
      user('Fix the flaky login test'),
    ]);
    expect(provider.extractSessionLabel(file)).toBe('Fix the flaky login test');
    expect((await provider.extractSessionLabelsAsync([file])).get(file)).toBe(
      'Fix the flaky login test',
    );
  });

  it('reads slash commands as typed and unwraps pasted content', () => {
    const command = transcript('-w-app', [
      user(
        '<command-message>review</command-message>\n<command-name>/review</command-name>\n<command-args>src/app.ts</command-args>',
      ),
    ]);
    expect(provider.extractSessionLabel(command)).toBe('/review src/app.ts');

    const pasted = transcript('-w-app', [
      user('<pasted_content id="c00d">\nPlease consider the following error\n</pasted_content>'),
    ]);
    expect(provider.extractSessionLabel(pasted)).toBe('Please consider the following error');
  });

  it('keeps the 60-character cut', () => {
    const file = transcript('-w-app', [user('x'.repeat(200))]);
    expect(provider.extractSessionLabel(file)).toBe(`${'x'.repeat(57)}...`);
  });

  it('finds a first prompt that starts after the first 8 KB', async () => {
    const file = transcript('-w-app', [
      user(`<local-command-stdout>${'o'.repeat(12_000)}</local-command-stdout>`),
      user('The real question'),
    ]);
    expect(provider.extractSessionLabel(file)).toBe('The real question');
    expect((await provider.extractSessionLabelsAsync([file])).get(file)).toBe('The real question');
  });

  it('labels from session events the same way', () => {
    const events = [
      user('<task-notification>agent done</task-notification>'),
      user('hidden', { isSidechain: true }),
      user('Ship the release'),
    ] as unknown as SessionEvent[];
    expect(firstUserPrompt(events)).toBe('Ship the release');
  });
});

describe('Claude Code search hits', () => {
  const provider = new ClaudeCodeProvider();

  it('report the real project path, even from a subdirectory, and skip request blobs', () => {
    const file = transcript('-w-sidekick-agent-hub', [
      user('find the needle', { cwd: '/w/sidekick-agent-hub/packages/cli' }),
      { type: 'api-request-blob', message: { role: 'user', content: 'find the needle' } },
    ]);
    const hits = provider.searchInSession(file, 'needle', 10);
    expect(hits).toHaveLength(1);
    expect(hits[0].projectPath).toBe('/w/sidekick-agent-hub');
  });

  it('fall back to the decoded directory name without a cwd', () => {
    const file = transcript('-w-app', [user('find the needle')]);
    expect(provider.searchInSession(file, 'needle', 10)[0].projectPath).toBe('/w/app');
  });
});
